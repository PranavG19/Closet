#!/usr/bin/env node
// gen-conventions.mjs — derive every cross-cutting artifact from conventions.json.
//
// conventions.json is the SINGLE SOURCE OF TRUTH. This script regenerates:
//   - manifest.json                    (O(1) module → public-barrel symbol map;
//                                        barrel-less modules map to exports: [])
//   - .github/CODEOWNERS                (from conventions.humanOwnedPaths)
//   - gate-budget.json                 (from conventions.gateBudget)
//   - eslint.config.mjs FEATURE_ROOTS  (from conventions.featureRoots, between markers)
//
// Every generated file / region carries a DO-NOT-EDIT stamp. Hand-edit
// conventions.json (or, for the manifest, the source tree) and re-run `pnpm gen`.
//
// Modes:
//   (default)   write all generated files
//   --check     write nothing; exit 1 if any generated file would change
//               (the staleness gate wired into `pnpm verify`)
//
// Contract: byte-deterministic. Same inputs → identical outputs.
// Ported from fitapp/scripts/gen-conventions.mjs (scope @fitapp → @closet).

import { readdirSync, readFileSync, existsSync, writeFileSync, mkdirSync } from "node:fs";
import { join, resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const REPO_ROOT = resolve(fileURLToPath(import.meta.url), "..", "..");
const CHECK = process.argv.includes("--check");
const SCOPE = "@closet";

const conventions = JSON.parse(
  readFileSync(join(REPO_ROOT, "conventions.json"), "utf8"),
);

// ---------------------------------------------------------------------------
// Shared: stable JSON stringify (sorted keys, 2-space) — byte-deterministic.
// ---------------------------------------------------------------------------
function stableStringify(value, indent = 2) {
  const walk = (v, depth) => {
    const pad = " ".repeat(indent * depth);
    const nextPad = " ".repeat(indent * (depth + 1));
    if (v === null || typeof v !== "object") return JSON.stringify(v);
    if (Array.isArray(v)) {
      if (v.length === 0) return "[]";
      const items = v.map((el) => nextPad + walk(el, depth + 1));
      return "[\n" + items.join(",\n") + "\n" + pad + "]";
    }
    const keys = Object.keys(v).sort();
    if (keys.length === 0) return "{}";
    const entries = keys.map(
      (k) => nextPad + JSON.stringify(k) + ": " + walk(v[k], depth + 1),
    );
    return "{\n" + entries.join(",\n") + "\n" + pad + "}";
  };
  return walk(value, 0) + "\n";
}

// ---------------------------------------------------------------------------
// manifest.json — scan each module's public barrel; barrel-less → exports: [].
// ---------------------------------------------------------------------------
function listDirs(abs) {
  if (!existsSync(abs)) return [];
  return readdirSync(abs, { withFileTypes: true })
    .filter((e) => e.isDirectory() && !e.name.startsWith("."))
    .map((e) => e.name)
    .sort();
}

function entryFile(moduleAbs) {
  return [join(moduleAbs, "src", "index.ts"), join(moduleAbs, "index.ts")].find(
    (p) => existsSync(p),
  ) ?? null;
}

function extractExports(filePath) {
  const src = readFileSync(filePath, "utf8");
  const names = new Set();
  const declRe =
    /^\s*export\s+(?:async\s+)?(?:const|let|var|function\*?|class|type|interface|enum)\s+([A-Za-z_$][\w$]*)/gm;
  for (const m of src.matchAll(declRe)) names.add(m[1]);
  const braceRe = /^\s*export\s+(?:type\s+)?\{([^}]*)\}/gm;
  for (const m of src.matchAll(braceRe)) {
    for (const part of m[1].split(",")) {
      const seg = part.trim().replace(/^type\s+/, "");
      if (!seg) continue;
      const asMatch = /\s+as\s+([A-Za-z_$][\w$]*)\s*$/.exec(seg);
      if (asMatch) names.add(asMatch[1]);
      else {
        const bare = /^([A-Za-z_$][\w$]*)/.exec(seg);
        if (bare) names.add(bare[1]);
      }
    }
  }
  if (/^\s*export\s+default\b/m.test(src)) names.add("default");
  const nsRe = /^\s*export\s+\*\s+as\s+([A-Za-z_$][\w$]*)\s+from\b/gm;
  for (const m of src.matchAll(nsRe)) names.add(m[1]);
  return [...names].sort();
}

function collectModule(name, absPath) {
  const entry = entryFile(absPath);
  return {
    name,
    path: absPath.slice(REPO_ROOT.length + 1),
    entry: entry ? entry.slice(REPO_ROOT.length + 1) : null,
    exports: entry ? extractExports(entry) : [],
  };
}

function buildManifest() {
  const packagesDir = join(REPO_ROOT, "packages");
  const packageModules = listDirs(packagesDir).map((name) =>
    collectModule(`${SCOPE}/${name}`, join(packagesDir, name)),
  );
  const featuresDir = join(packagesDir, "mobile", "features");
  const featureModules = listDirs(featuresDir).map((name) =>
    collectModule(`${SCOPE}/mobile/features/${name}`, join(featuresDir, name)),
  );
  return stableStringify({
    $comment:
      "GENERATED by scripts/gen-conventions.mjs — DO NOT EDIT; run `pnpm gen`. " +
      "Maps each module to the symbols re-exported from its PUBLIC BARREL (src/index.ts or index.ts). " +
      "`entry: null` = no barrel; `exports: []` = a barrel that re-exports nothing (consumed via subpath). " +
      "A symbol absent here is proof of non-existence ONLY for modules with a barrel.",
    generatedBy: "scripts/gen-conventions.mjs",
    schemaVersion: 1,
    packages: packageModules,
    features: featureModules,
  });
}

// ---------------------------------------------------------------------------
// CODEOWNERS — from conventions.humanOwnedPaths.
// ---------------------------------------------------------------------------
function buildCodeowners() {
  const { owner, paths } = conventions.humanOwnedPaths;
  const lines = [
    "# CODEOWNERS — GENERATED by scripts/gen-conventions.mjs from conventions.json. DO NOT EDIT.",
    "# Edit conventions.json (humanOwnedPaths) and run `pnpm gen`.",
    "#",
    `# These paths require approval from ${owner} (the human principal).`,
    "# The agent token does NOT have write access to these paths.",
    "# PARKED: not enforced until a GitHub remote + branch protection ruleset exist.",
    "",
  ];
  const width = Math.max(...paths.map((p) => p.path.length));
  for (const { path, why } of paths) {
    lines.push(`# ${why}`);
    lines.push(`${path.padEnd(width)}  ${owner}`);
  }
  return lines.join("\n") + "\n";
}

// ---------------------------------------------------------------------------
// gate-budget.json — from conventions.gateBudget.
// ---------------------------------------------------------------------------
function buildGateBudget() {
  const { maxBudget, gates } = conventions.gateBudget;
  return stableStringify({
    $comment:
      "GENERATED by scripts/gen-conventions.mjs from conventions.json. DO NOT EDIT. Weights: structural=0, mechanical=1, advisory=2. Synchronous weights must sum to <= maxBudget; async gates run post-merge and are excluded.",
    generatedBy: "scripts/gen-conventions.mjs",
    maxBudget,
    gates,
  });
}

// ---------------------------------------------------------------------------
// eslint.config.mjs FEATURE_ROOTS — replace the array between markers only.
// ---------------------------------------------------------------------------
const ESLINT_BEGIN = "// <<< GENERATED FEATURE_ROOTS (gen-conventions.mjs) — DO NOT EDIT >>>";
const ESLINT_END = "// <<< END GENERATED FEATURE_ROOTS >>>";

function buildEslintRegion() {
  const roots = conventions.featureRoots.roots;
  const body = roots.map((r) => `  ${JSON.stringify(r)},`).join("\n");
  return `${ESLINT_BEGIN}\nconst FEATURE_ROOTS = [\n${body}\n];\n${ESLINT_END}`;
}

function injectEslint(current) {
  const region = buildEslintRegion();
  const b = current.indexOf(ESLINT_BEGIN);
  const e = current.indexOf(ESLINT_END);
  if (b === -1 || e === -1) {
    throw new Error(
      "eslint.config.mjs is missing the FEATURE_ROOTS generation markers. Add:\n" +
        ESLINT_BEGIN + "\n...\n" + ESLINT_END +
        "\naround the FEATURE_ROOTS declaration, then re-run.",
    );
  }
  return current.slice(0, b) + region + current.slice(e + ESLINT_END.length);
}

// ---------------------------------------------------------------------------
// Drive: compute desired content for each target, then write or check.
// ---------------------------------------------------------------------------
const eslintPath = join(REPO_ROOT, "eslint.config.mjs");
const targets = [
  { path: join(REPO_ROOT, "manifest.json"), desired: buildManifest() },
  { path: join(REPO_ROOT, ".github", "CODEOWNERS"), desired: buildCodeowners() },
  { path: join(REPO_ROOT, "gate-budget.json"), desired: buildGateBudget() },
  { path: eslintPath, desired: injectEslint(readFileSync(eslintPath, "utf8")) },
];

let stale = 0;
for (const { path, desired } of targets) {
  const rel = path.slice(REPO_ROOT.length + 1);
  const current = existsSync(path) ? readFileSync(path, "utf8") : null;
  if (current === desired) continue;
  stale += 1;
  if (CHECK) {
    process.stderr.write(`STALE: ${rel} — run \`pnpm gen\`\n`);
  } else {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, desired);
    process.stdout.write(`wrote ${rel}\n`);
  }
}

if (CHECK) {
  if (stale > 0) {
    process.stderr.write(
      `\ngen:check failed — ${stale} generated file(s) stale. Run \`pnpm gen\` and commit.\n`,
    );
    process.exit(1);
  }
  process.stdout.write("gen:check: all generated files up to date\n");
} else if (stale === 0) {
  process.stdout.write("gen: all generated files already up to date\n");
}
